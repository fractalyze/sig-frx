"""LeanSig Poseidon permutation vectors, transcribed from leanSpec's fixtures.

leanSig publishes no RFC/FIPS/EIP and no vector file of its own, so the authority
is the reference implementation the spec points at — third in the order
[`conventions.md`](../../../../docs/reference/conventions.md) fixes. leanSpec does
generate these, and they gate the permutation directly rather than through a
whole signature, which is what the acceptance rule asks for.

## Provenance

- **Upstream:** `leanEthereum/leanSpec` at commit
  `0588c2d215a955a516378677a92db2a5666802f3`.
- **Fixture:** the release asset `fixtures-prod-scheme.tar.gz`, paths
  `fixtures/consensus/poseidon_permutation/lstar/poseidon/test_permutation_width{16,24}/*.json`,
  one file per vector named as the vector below is.
- **The exact call each value came from:** `inputState` and `outputState`
  verbatim, as canonical field residues.

## Why transcribed rather than fetched

[`conventions.md`](../../../../docs/reference/conventions.md) has vector sets
fetched and pinned, with the URL pinned to a commit — "a moving URL turns an
upstream regeneration into a mystery failure here". leanSpec publishes its
fixtures under a release tag literally named `latest`, regenerated in place on
every spec commit, so there is no commit-pinned URL to name. Transcribing is the
rule's own remedy for values that have nothing stable to fetch: the archive is
also 154 MB, of which these eight vectors are a few kilobytes.

The remaining families in that archive do not gate this scheme. Its
signature-shaped fixtures carry a leanMultisig **aggregate proof** rather than an
XMSS signature, so a scheme-level vector has to be produced by running leanSpec
against its published keys.
"""

