"""LeanSig's Poseidon constants, transcribed from leanSpec.

LeanSig hashes with **classic Poseidon** ([eprint 2019/458], the Hades design),
not Poseidon2 — the technical note ([eprint 2025/1332] §5) recommends Poseidon2,
and the shipped spec does not follow it. Two widths are used: 16 for the chain
hash, 24 for the message, tree and leaf hashes.

These constants are one scheme's, so they live here rather than in hash-frx,
whose rule for a named set is "is this set one scheme's?"
(`hash_frx/poseidon2/standard.py`). The table below is upstream's values
verbatim, in upstream's own lane-0 orientation, so a reader can diff it against
the spec; [`poseidon.py`](poseidon.py) does the conjugation that bridges it to
hash-frx's last-lane convention, for the reason recorded on
[#195](https://github.com/fractalyze/sig-frx/issues/195).

## Provenance

- **Upstream:** `leanEthereum/leanSpec` at commit
  `0588c2d215a955a516378677a92db2a5666802f3` —
  the commit the `latest` production fixtures were generated from. leanSig has
  no RFC/FIPS/EIP, so the authority is the reference implementation the spec
  points at, which is what
  [`conventions.md`](../../../docs/reference/conventions.md) names third.
- **Fixture:** `src/lean_spec/spec/crypto/poseidon.py`.
- **The exact call each value came from:** none — these are source constants,
  read out of that module verbatim. What produced this file:

  ```python
  import ast
  tree = ast.parse(open("poseidon.py").read())
  values = {
      node.target.id: ast.literal_eval(node.value)
      for node in tree.body
      if isinstance(node, ast.AnnAssign)
      and node.target.id.startswith(("_RAW_CONSTANTS", "_MDS_FIRST_ROW"))
  }
  ```

The round-constant tables are flat and row-major: `(rounds_f + rounds_p)` rows of
`width` values, one ARC vector per round, full and partial rounds alike. The MDS
is circulant and given by its first row `r`, with `M[i][j] = r[(j - i) mod p]` —
row `i` is `r` rolled right by `i`.
"""

